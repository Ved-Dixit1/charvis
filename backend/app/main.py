# --- Background Task Runners ---

def run_pipeline_in_background(execution_id: str, db_session_maker):
    """
    Background worker that executes the pipeline and commits output logs.
    Creates a new database session to avoid thread sharing conflicts.
    """
    db = db_session_maker()
    try:
        executor = PipelineExecutor(db=db, execution_id=execution_id)
        executor.execute()
    except Exception as e:
        logger.error(f"Background execution failed: {str(e)}")
    finally:
        db.close()


def run_model_download_in_background(model_id: str, preferred_quant: str):
    """Background worker to download large GGUF checkpoints."""
    try:
        hf_client.resolve_and_download_gguf(model_id, preferred_quant)
    except Exception as e:
        logger.error(f"Background download failed for '{model_id}': {str(e)}")


