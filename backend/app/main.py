@app.get("/api/models/cache")
def api_get_cached_models():
    """Scans the local HF directory and returns a breakdown of cached repositories."""
    try:
        from huggingface_hub import scan_cache_dir
        cache_info = scan_cache_dir(cache_dir=settings.hf_cache_path)
        cached_repos = []
        for repo in cache_info.repos:
            files = []
            for revision in repo.revisions:
                for file in revision.files:
                    files.append({
                        "filename": file.file_name,
                        "size": file.size,
                        "path": str(file.file_path)
                    })
            cached_repos.append({
                "repo_id": repo.repo_id,
                "repo_type": repo.repo_type,
                "size_on_disk": repo.size_on_disk,
                "size_str": f"{repo.size_on_disk / (1024*1024*1024):.2f} GB",
                "files": files
            })
        return {"cached_dir": settings.hf_cache_path, "repos": cached_repos}
    except Exception as e:
        logger.error(f"Failed to scan cache directory: {str(e)}")
        return {"cached_dir": settings.hf_cache_path, "repos": [], "error": str(e)}


@app.post("/api/models/download")
def api_download_model(
    model_id: str, 
    preferred_quant: str = "q4_k_m", 
    background_tasks: BackgroundTasks = BackgroundTasks()
):
    """Triggers download of a model file in a background worker."""
    if not hf_client.verify_model_exists(model_id):
        raise HTTPException(status_code=400, detail=f"Model '{model_id}' does not exist on the Hugging Face Hub.")

    background_tasks.add_task(run_model_download_in_background, model_id, preferred_quant)
    return {
        "status": "queued",
        "message": f"Background download process initiated for model '{model_id}' targeting quantization format '{preferred_quant}'."
    }
